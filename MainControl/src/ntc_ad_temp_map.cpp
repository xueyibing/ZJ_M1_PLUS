int applyTempOffset(int tempValue, int offsetC)
{
  int adjusted = tempValue + offsetC;
  if (adjusted < TEMP_MIN)
  {
    return TEMP_MIN;
  }
  if (adjusted > TEMP_MAX)
  {
    return TEMP_MAX;
  }
  return adjusted;
}

int downAdToEquivalent20KUpAd(int adcValue, int pullDownOhm)
{
  if (adcValue <= 0)
  {
    return ADC_MAX;
  }
  if (adcValue >= ADC_MAX)
  {
    return 0;
  }

  int64_t numerator = (int64_t)ADC_MAX * pullDownOhm * (ADC_MAX - adcValue);
  int64_t denominator = (int64_t)PULLUP_20K_OHM * adcValue + (int64_t)pullDownOhm * (ADC_MAX - adcValue);
  return (int)((numerator + denominator / 2) / denominator);
}

