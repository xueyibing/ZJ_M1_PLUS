int adToTemp20KUpBase(int adcValue)
{
  if (adcValue >= AD_UP_20K[0])
  {
    return TEMP_MIN;
  }
  if (adcValue <= AD_UP_20K[TABLE_N - 1])
  {
    return TEMP_MAX;
  }
  // 二分：AD_UP_20K[hi] <= adcValue < AD_UP_20K[lo]
  int lo = 0;
  int hi = TABLE_N - 1;
  while (hi - lo > 1)
  {
    int mid = (lo + hi) >> 1;
    if (AD_UP_20K[mid] > adcValue)
    {
      lo = mid;
    }
    else
    {
      hi = mid;
    }
  }
  int ad_lo = AD_UP_20K[lo]; // 较大
  int ad_hi = AD_UP_20K[hi]; // 较小
  int t_lo  = TEMP_MIN + lo;
  int span  = ad_lo - ad_hi;
  if (span <= 0)
  {
    return t_lo;
  }
  int delta = ad_lo - adcValue;
  return t_lo + (delta + span / 2) / span;
}
