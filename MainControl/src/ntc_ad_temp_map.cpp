// 下拉接法：表为单调递增
int adToTemp3KDown(int adcValue)
{
  if (adcValue <= AD_DOWN_3K[0])
  {
    return applyTempOffset(TEMP_MIN, NTC_3K_DOWN_TEMP_OFFSET_C);
  }
  if (adcValue >= AD_DOWN_3K[TABLE_N - 1])
  {
    return applyTempOffset(TEMP_MAX, NTC_3K_DOWN_TEMP_OFFSET_C);
  }
  // 二分：AD_DOWN_3K[lo] <= adcValue < AD_DOWN_3K[hi]
  int lo = 0;
  int hi = TABLE_N - 1;
  while (hi - lo > 1)
  {
    int mid = (lo + hi) >> 1;
    if (AD_DOWN_3K[mid] <= adcValue)
    {
      lo = mid;
    }
    else
    {
      hi = mid;
    }
  }
  int ad_lo = AD_DOWN_3K[lo]; // 较小
  int ad_hi = AD_DOWN_3K[hi]; // 较大
  int t_lo  = TEMP_MIN + lo;
  int span  = ad_hi - ad_lo;
  if (span <= 0)
  {
    return applyTempOffset(t_lo, NTC_3K_DOWN_TEMP_OFFSET_C);
  }
  int delta = adcValue - ad_lo;
  return applyTempOffset(t_lo + (delta + span / 2) / span, NTC_3K_DOWN_TEMP_OFFSET_C);
}

int adToTemp5K1Down(int adcValue)
{
  int equivalent20KUpAd = downAdToEquivalent20KUpAd(adcValue, PULLDOWN_5K1_OHM);
  return applyTempOffset(adToTemp20KUpBase(equivalent20KUpAd), NTC_5K1_DOWN_TEMP_OFFSET_C);
}

int adToTemp20KUp(int adcValue)
{
  return applyTempOffset(adToTemp20KUpBase(adcValue), NTC_20K_UP_TEMP_OFFSET_C);
}

